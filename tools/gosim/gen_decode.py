#!/usr/bin/env python3
"""Generate the Go decode table and model-id data from the pinned pi32v2 table.

Read-only generator: consumes tools/reference-cache/pi32v2-isa/isa/pi32v2.toml
(the pinned upstream table) and emits Go sources. The upstream tree is never
modified. The block-model parameters and the memop/rmw id lists replicate the
upstream semantics modules' registration logic (semantics/v3.py, v4.py, v5.py,
m2.py + the missing-file adapter in probe_pi32v2.upstream).

Run from the repo root:
    python3 tools/gosim/gen_decode.py
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools" / "reference-cache" / "pi32v2-isa"))
from pi32v2isa import table  # noqa: E402

CACHE = ROOT / "tools" / "reference-cache" / "pi32v2-isa"

BRANCH_RE = re.compile(r"\b(?:goto|call|gotoss) \{(\w)\}(?: \(\w\))?$")
BLOCK_RE = re.compile(r"(iff|ifs|if) \(\(?\{r\} (?:& \{[sn]\}\) )?(u?)(==|!=|>=|<=|<|>) (?:\{[sn]\}|0)\)? \{\{")
REL = {"==": "eq", "!=": "ne", ">=": "ge", "<": "lt", ">": "gt", "<=": "le"}


def go_str(s):
    out = ['"']
    for ch in s:
        if ch == '"':
            out.append('\\"')
        elif ch == '\\':
            out.append('\\\\')
        elif ch == '\n':
            out.append('\\n')
        elif ch == '\t':
            out.append('\\t')
        elif 32 <= ord(ch) < 127:
            out.append(ch)
        else:
            out.append(f'\\u{ord(ch):04x}')
    out.append('"')
    return ''.join(out)


def go_bool(b):
    return "true" if b else "false"


def block_models(tab):
    """[(id, condition, signed, masked, floating, and_block)] for every block opener."""
    out = []
    for i in tab.insns:
        if not i.block or i.id.endswith(".p") or i.asm_no_syntax or re.fullmatch(r"iff\.ne\.rr\.\d", i.id):
            continue
        m = BLOCK_RE.match(i.syntax)
        if not m:
            continue
        kind, u, rel = m.groups()
        condition = u + REL[rel]
        out.append((i.id, condition, kind == "ifs", "&" in i.syntax, kind == "iff", False))
    for n in range(1, 7):
        out.append((f"iff.ne.rr.{n}", "ne", False, True, False, False))
    for n in range(1, 8):
        out.append((f"if.unknown.rr.{n}", "", False, False, False, True))
    return out


def memop_rmw_ids():
    """memop/rmw id lists, exactly as probe_pi32v2.upstream feeds m2.py."""
    sys.path.insert(0, str(ROOT / "tools"))
    sys.path.insert(0, str(ROOT / "tools" / "reference-cache" / "pi32v2-isa" / "tools" / "hwtest"))
    import importlib
    nonm2 = {}
    for p in sorted((CACHE / "tools" / "hwtest" / "semantics").glob("*.py")):
        if p.stem.startswith("_") or p.stem == "m2":
            continue
        mod = importlib.import_module("semantics." + p.stem)
        nonm2.update(mod.MODELS)
    ids = set()
    for path in (CACHE / "hw" / "fm1-2026-10-24-v2").glob("*.jsonl"):
        for line in path.read_text().splitlines():
            rec = json.loads(line)
            if rec.get("id") and rec["id"] not in nonm2:
                ids.add(rec["id"])
    memop = sorted(i for i in ids if i.startswith(("ld.", "st."))
                   and not i.startswith(("ld.w.npc", "st.w.modimm")))
    rmw = sorted(i for i in ids if i.startswith("rmw."))
    return memop, rmw


def main():
    tab = table.load()
    here = Path(__file__).resolve().parent

    # ---- decode_table.go ---------------------------------------------------
    lines = []
    w = lines.append
    w("// Code generated by tools/gosim/gen_decode.py from the pinned")
    w("// pi32v2-isa table (isa/pi32v2.toml). DO NOT EDIT BY HAND.")
    w("")
    w("package gosim")
    w("")
    w("type fieldMeta struct {")
    w("\tname    string")
    w("\tkind    string")
    w("\tpos     []uint8 // bit positions, most significant first (0 = MSB of encoding)")
    w("\tscale   int")
    w("\tadd     int")
    w("\tinvert  bool")
    w("\tdecimal bool // modimm only: printed as signed decimal")
    w("\tlead    string // rmask only")
    w("\tzeroAs  int // -1 when absent")
    w("\tenums   []string")
    w("\twidth   int")
    w("}")
    w("")
    w("type insnMeta struct {")
    w("\tid        string")
    w("\tsyntax    string")
    w("\tnwords    int")
    w("\tmask      uint64")
    w("\tvalue     uint64")
    w("\tfields    []fieldMeta")
    w("\tbranch    string // pc-relative target field (goto/call/gotoss {n}), \"\" when none")
    w("\tblockThen string // if-block opener: then-count field")
    w("\tblockElse string // if-block opener: else-count field")
    w("\tbody      string // rep/rep.i body-length field")
    w("}")
    w("")
    w("var decodeTable = []insnMeta{")
    for insn in tab.insns:
        mask = insn.mask
        value = insn.value
        fields = []
        for name, f in insn.fields.items():
            pos = insn.field_bits(name)
            zero_as = f.zero_as if f.zero_as is not None else -1
            enums = "nil"
            if f.kind == "enum":
                enums = "[]string{" + ", ".join(go_str(v) for v in f.values) + "}"
            fields.append((name, f.kind, pos, f.scale, f.add, f.invert, f.decimal, f.lead, zero_as, enums))
        branch = ""
        m = BRANCH_RE.search(insn.syntax)
        if m and insn.fields[m.group(1)].kind == "simm":
            branch = m.group(1)
        w("\t{")
        w(f"\t\tid:        {go_str(insn.id)},")
        w(f"\t\tsyntax:    {go_str(insn.syntax)},")
        w(f"\t\tnwords:    {len(insn.words)},")
        w(f"\t\tmask:      0x{mask:012x},")
        w(f"\t\tvalue:     0x{value:012x},")
        w("\t\tfields: []fieldMeta{")
        for name, kind, pos, scale, add, invert, decimal, lead, zero_as, enums in fields:
            pos_lit = "[]uint8{" + ",".join(str(p) for p in pos) + "}"
            w(f"\t\t\t{{name: {go_str(name)}, kind: {go_str(kind)}, pos: {pos_lit}, "
              f"scale: {scale}, add: {add}, invert: {go_bool(invert)}, decimal: {go_bool(decimal)}, "
              f"lead: {go_str(lead)}, zeroAs: {zero_as}, enums: {enums}, width: {len(pos)}}},")
        w("\t\t},")
        w(f"\t\tbranch:    {go_str(branch)},")
        w(f"\t\tblockThen: {go_str(insn.block.get('then', ''))},")
        w(f"\t\tblockElse: {go_str(insn.block.get('else', ''))},")
        w(f"\t\tbody:      {go_str(insn.body)},")
        w("\t},")
    w("}")
    (here / "decode_table.go").write_text("\n".join(lines) + "\n")

    # ---- model_gen.go ------------------------------------------------------
    memop_ids, rmw_ids = memop_rmw_ids()
    blocks = block_models(tab)
    lines = []
    w = lines.append
    w("// Code generated by tools/gosim/gen_decode.py. DO NOT EDIT BY HAND.")
    w("")
    w("package gosim")
    w("")
    w("// memopIDs / rmwIDs are the ld/st and rmw instruction ids whose models are")
    w("// built by semantics.m2 (fed the hardware-record id list by the upstream")
    w("// missing-file adapter).")
    w("var memopIDs = []string{")
    for i in memop_ids:
        w(f"\t{go_str(i)},")
    w("}")
    w("")
    w("var rmwIDs = []string{")
    for i in rmw_ids:
        w(f"\t{go_str(i)},")
    w("}")
    w("")
    w("type blockModelSpec struct {")
    w("\tid        string")
    w("\tcondition string")
    w("\tsignedCmp bool")
    w("\tmasked    bool")
    w("\tfloating  bool")
    w("\tandBlock  bool // v4 and_block: taken = !(r & s)")
    w("}")
    w("")
    w("var blockModels = []blockModelSpec{")
    for id_, cond, signed, masked, floating, and_block in blocks:
        w(f"\t{{id: {go_str(id_)}, condition: {go_str(cond)}, signedCmp: {go_bool(signed)}, "
          f"masked: {go_bool(masked)}, floating: {go_bool(floating)}, andBlock: {go_bool(and_block)}}},")
    w("}")
    (here / "model_gen.go").write_text("\n".join(lines) + "\n")

    print(f"decode_table.go: {len(tab.insns)} instructions")
    print(f"model_gen.go: {len(memop_ids)} memop, {len(rmw_ids)} rmw, {len(blocks)} block models")


if __name__ == "__main__":
    main()
