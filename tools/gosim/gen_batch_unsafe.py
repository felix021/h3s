#!/usr/bin/env python3
"""Regenerate tools/gosim/batch_unsafe.go from the pinned pi32v2-isa table.

The stage-1 segment batch (tools/gosim/segment.go) runs only "single-core
sequential scalar ALU" instructions. This script computes the deny set once
from the instruction table and writes it as a Go map; segment.go adds the
structural branch/if-block/rep/.p checks on top.

Denied: every instruction whose group is not in the allowed scalar-ALU set,
plus special-register (sr) fields, sp/bank moves, and .p parallel pairs.
Allowed groups: arithmetic, logic, shifts, bitops, moves, constants, multiply,
fpu. Everything else (memory, stack, cache, branches, jumps, returns, control,
dsp) stays out of the stage-1 contract.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools" / "reference-cache" / "pi32v2-isa"))
sys.path.insert(0, str(ROOT / "tools" / "reference-cache" / "pi32v2-isa" / "pi32v2isa"))

from pi32v2isa import table as T  # noqa: E402
from pi32v2isa import asm  # noqa: E402

ALLOWED = {"arithmetic", "logic", "shifts", "bitops", "moves", "constants", "multiply", "fpu"}
SP_BANK = {"add.sp_i", "add.sp_i.l", "add.r_sp_i", "add.r_sp_i.l"}


def is_unsafe(insn):
    if insn.group not in ALLOWED:
        return True
    if any(f.kind == "sr" for f in insn.fields.values()):
        return True
    if insn.id in SP_BANK or insn.id.startswith(("mov.sp_", "mov.ssp_", "mov.usp_")):
        return True
    if insn.id.endswith(".p"):
        return True
    if asm.branch_field(insn) is not None or insn.block or getattr(insn, "body", ""):
        return True
    return False


def main():
    tab = T.load()
    unsafe = sorted({i.id for i in tab.insns if is_unsafe(i)})
    lines = [
        "package gosim",
        "",
        "// batchUnsafe is the stage-1 segment-batch deny set, generated by",
        "// gen_batch_unsafe.py from the pinned pi32v2-isa table",
        "// (tools/reference-cache). A segment step is rejected when its decoded",
        "// instruction id is in this set, or when insnMeta marks it as branch /",
        "// if-block / rep / .p parallel (checked structurally in segment.go; this",
        "// map adds the memory/stack/cache/control/dsp/special-register/sp-bank",
        "// families that carry no such marker).",
        "var batchUnsafe = map[string]bool{",
    ]
    for uid in unsafe:
        lines.append(f'\t"{uid}": true,')
    lines.append("}")
    out = ROOT / "tools" / "gosim" / "batch_unsafe.go"
    out.write_text("\n".join(lines) + "\n")
    safe = [i.id for i in tab.insns if i.id not in set(unsafe)]
    print(f"total={len(tab.insns)} unsafe={len(unsafe)} safe={len(safe)} -> {out}")


if __name__ == "__main__":
    main()
